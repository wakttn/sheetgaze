use crate::domain::edit::{EditCommit, EditCursor};
use crate::domain::register::{PasteSource, RegisterKind};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Motion {
    Up,
    Down,
    Left,
    Right,
    PageUp,
    PageDown,
    HalfUp,
    HalfDown,
    Top,
    Bottom,
    DataTop,
    DataBottom,
    LineStart,
    LineEnd,
    FirstNonBlank,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ClipboardWriteOrigin {
    Register { kind: RegisterKind },
    PlainCopy,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Action {
    Move(Motion),
    Extend(Motion),
    ToggleVisual,
    ToggleLineVisual,
    ToggleColumnVisual,
    ToggleBlockVisual,
    ToggleFitWidth,
    Copy,
    YankRow,
    OpenDetail,
    CloseDetail,
    ScrollDetail(i32),
    SwitchSheet(i32),
    SearchOpen,
    SearchInput(char),
    SearchBackspace,
    SearchSubmit,
    SearchCancel,
    SearchNext,
    SearchPrevious,
    FilterOpen,
    FilterMove(i32),
    FilterToggle,
    FilterToggleAll,
    FilterClear,
    FilterClose,
    Reload,
    ReloadForce,
    Save {
        force: bool,
        quit_after: bool,
    },
    EditStart(EditCursor),
    EditClear,
    EditFormula,
    EditInput(char),
    EditBackspace,
    EditDelete,
    EditLeft,
    EditRight,
    EditHome,
    EditEnd,
    EditDeleteWord,
    EditDeleteToStart,
    EditCommit(EditCommit),
    EditCancel,
    CommandOpen,
    CommandInput(char),
    CommandBackspace,
    CommandHistory(i32),
    CommandSubmit,
    CommandCancel,
    Undo,
    Redo,
    ClearCell,
    ClearRow,
    ClearMotion(Motion),
    Cut,
    CutRow,
    CutSelection,
    CutMotion(Motion),
    Paste {
        before: bool,
        source: PasteSource,
    },
    InsertRows {
        before: bool,
        enter_insert: bool,
        count: u32,
    },
    InsertColumns {
        before: bool,
        enter_insert: bool,
        count: u32,
    },
    DeleteRows {
        before: bool,
        count: u32,
    },
    DeleteColumns {
        before: bool,
        count: u32,
    },
    ReplaceChar(char),
    SearchWord(bool),
    JumpBack,
    JumpForward,
    ForceQuit,
    HelpOpen,
    HelpClose,
    Resize(u16, u16),
    Quit,
}

#[derive(Clone, Debug)]
pub enum Effect {
    WriteClipboard {
        text: String,
        origin: ClipboardWriteOrigin,
    },
    ReadClipboard {
        before: bool,
        fallback: Option<PasteSource>,
    },
    SetStatus(String),
    Reload,
    Save {
        force: bool,
        quit_after: bool,
    },
    Quit,
}
